#!/usr/bin/env python3

"""Generate visible soft vegetation across the Lehrforst tree area."""

import csv
import math
import os
import random
from sys import argv


MODEL_NAME = "soft_vegetation_forest"
RANDOM_SEED = "lehrforst-soft-vegetation-v1"

SOURCE_X_MIN = 10.0
SOURCE_X_MAX = 70.0
SOURCE_Y_MIN = -30.0
SOURCE_Y_MAX = 30.0
TREE_MIN_DIAMETER_CM = 7.0
LEHRFORST_WORLD_X_OFFSET = 42.0

BUSH_COUNT = 300
TREE_CLEARANCE = 1.35
BUSH_CLEARANCE = 0.95
SCOUT_START = (0.0, 2.118)
SCOUT_CLEARANCE = 1.1
DEMO_LANE_Y = 2.118
DEMO_LANE_X_MIN = -0.8
DEMO_LANE_X_MAX = 11.2
DEMO_LANE_CLEARANCE = 1.25


def load_tree_points(model_path):
    tree_csv = os.path.join(model_path, "..", "lehrforst_trees", "tree_positions.csv")
    trees = []
    with open(tree_csv, newline="") as csv_file:
        for row in csv.DictReader(csv_file):
            source_x = float(row["x"])
            source_y = float(row["y"])
            source_z = float(row["z"])
            diameter = float(row["bhd"])
            if (
                diameter < TREE_MIN_DIAMETER_CM
                or not SOURCE_X_MIN < source_x < SOURCE_X_MAX
                or not SOURCE_Y_MIN < source_y < SOURCE_Y_MAX
            ):
                continue

            trees.append(
                {
                    "x": LEHRFORST_WORLD_X_OFFSET - source_x,
                    "y": source_y,
                    "z": -source_z,
                    "diameter": diameter,
                }
            )
    return trees


def distance_xy(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def nearest_tree(candidate, trees):
    return min(
        (
            (distance_xy(candidate, (tree["x"], tree["y"])), tree)
            for tree in trees
        ),
        key=lambda item: item[0],
    )


def make_bush(index, x, y, ground_z, nearest_tree_distance, rng):
    height = rng.uniform(0.85, 1.25)
    collision_radius = rng.uniform(0.12, 0.18)
    leaf_radius = rng.uniform(0.34, 0.52)
    yaw = rng.uniform(0.0, 2.0 * math.pi)

    return {
        "name": f"bush_{index:03d}",
        "x": x,
        "y": y,
        "ground_z": ground_z,
        "center_z": ground_z + height / 2.0,
        "height": height,
        "collision_radius": collision_radius,
        "leaf_radius": leaf_radius,
        "yaw": yaw,
        "nearest_tree_distance": nearest_tree_distance,
    }


def generate_positions(trees):
    rng = random.Random(RANDOM_SEED)
    accepted = []

    world_x_min = LEHRFORST_WORLD_X_OFFSET - SOURCE_X_MAX
    world_x_max = LEHRFORST_WORLD_X_OFFSET - SOURCE_X_MIN
    attempts = 0
    max_attempts = 50000

    while len(accepted) < BUSH_COUNT and attempts < max_attempts:
        attempts += 1
        x = rng.uniform(world_x_min, world_x_max)
        y = rng.uniform(SOURCE_Y_MIN, SOURCE_Y_MAX)
        nearest_distance, tree = nearest_tree((x, y), trees)

        if nearest_distance < TREE_CLEARANCE:
            continue
        if distance_xy((x, y), SCOUT_START) < SCOUT_CLEARANCE:
            continue
        if (
            DEMO_LANE_X_MIN <= x <= DEMO_LANE_X_MAX
            and abs(y - DEMO_LANE_Y) < DEMO_LANE_CLEARANCE
        ):
            continue
        if any(distance_xy((x, y), (bush["x"], bush["y"])) < BUSH_CLEARANCE for bush in accepted):
            continue

        accepted.append(make_bush(len(accepted), x, y, tree["z"], nearest_distance, rng))

    if len(accepted) != BUSH_COUNT:
        raise RuntimeError(
            f"Only generated {len(accepted)} bushes after {max_attempts} attempts"
        )

    return accepted


def bush_to_sdf(bush):
    height = bush["height"]
    leaf_z = height * 0.22

    return f"""
    <link name="{bush['name']}">
      <pose relative_to="__model__">{bush['x']:.3f} {bush['y']:.3f} {bush['center_z']:.3f} 0 0 {bush['yaw']:.3f}</pose>
      <visual name="stem_visual">
        <geometry>
          <cylinder>
            <radius>0.035</radius>
            <length>{height:.3f}</length>
          </cylinder>
        </geometry>
        <material>
          <ambient>0.07 0.33 0.08 1</ambient>
          <diffuse>0.10 0.55 0.12 1</diffuse>
          <specular>0.03 0.08 0.03 1</specular>
        </material>
      </visual>
      <visual name="leaf_cluster_visual">
        <pose>0 0 {leaf_z:.3f} 0 0 0</pose>
        <geometry>
          <sphere>
            <radius>{bush['leaf_radius']:.3f}</radius>
          </sphere>
        </geometry>
        <material>
          <ambient>0.04 0.30 0.07 1</ambient>
          <diffuse>0.08 0.58 0.13 1</diffuse>
          <specular>0.02 0.07 0.02 1</specular>
        </material>
      </visual>
    </link>
"""


def write_outputs(target_dir, bushes):
    os.makedirs(target_dir, exist_ok=True)

    sdf = """<?xml version="1.0" ?>
<!-- auto generated by generate_soft_vegetation_forest_model_sdf.py -->
<sdf version="1.10">
  <model name="soft_vegetation_forest">
    <static>true</static>
"""
    for bush in bushes:
        sdf += bush_to_sdf(bush)

    sdf += """
  </model>
</sdf>
"""

    with open(os.path.join(target_dir, "model.sdf"), "w") as sdf_file:
        sdf_file.write(sdf)

    with open(os.path.join(target_dir, "vegetation_positions.csv"), "w", newline="") as csv_file:
        writer = csv.writer(csv_file)
        writer.writerow(
            [
                "name",
                "x",
                "y",
                "ground_z",
                "height",
                "collision_radius",
                "leaf_radius",
                "nearest_tree_distance",
            ]
        )
        for bush in bushes:
            writer.writerow(
                [
                    bush["name"],
                    f"{bush['x']:.3f}",
                    f"{bush['y']:.3f}",
                    f"{bush['ground_z']:.3f}",
                    f"{bush['height']:.3f}",
                    f"{bush['collision_radius']:.3f}",
                    f"{bush['leaf_radius']:.3f}",
                    f"{bush['nearest_tree_distance']:.3f}",
                ]
            )


def main():
    model_path = os.path.dirname(__file__)
    target_dir = argv[1] if len(argv) > 1 else model_path
    trees = load_tree_points(model_path)
    bushes = generate_positions(trees)
    write_outputs(target_dir, bushes)


if __name__ == "__main__":
    main()
