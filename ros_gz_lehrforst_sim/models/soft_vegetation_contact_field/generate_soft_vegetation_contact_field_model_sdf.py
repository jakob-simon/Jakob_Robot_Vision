#!/usr/bin/env python3

"""Generate a compact spring-mounted vegetation contact field."""

import csv
import math
import os
import random
from sys import argv


RANDOM_SEED = "lehrforst-soft-vegetation-contact-v1"

# Hinterer Busch liegt auf der tatsaechlich gefahrenen Linie des Scout (er wird
# vom vorderen Busch nach unten gedrueckt und ist bei x=6.35 real bei y~1.77),
# nicht auf der nominellen Spur y=2.118. Sonst wird er verfehlt.
CONTACT_POINTS = [
    (1.60, 2.118),
    (6.35, 1.77),
]


def make_bush(index, x, y, rng):
    height = rng.uniform(1.04, 1.18)
    if index == 0:
        collision_radius = rng.uniform(0.075, 0.090)
        collision_length = rng.uniform(0.58, 0.68)
        spring_stiffness = rng.uniform(0.095, 0.165)
        damping = rng.uniform(0.050, 0.100)
    else:
        collision_radius = rng.uniform(0.115, 0.135)
        collision_length = rng.uniform(0.78, 0.90)
        spring_stiffness = rng.uniform(0.045, 0.075)
        damping = rng.uniform(0.020, 0.045)
    leaf_radius = rng.uniform(0.30, 0.40)
    center_z = height / 2.0
    yaw = rng.uniform(0.0, 2.0 * math.pi)
    mass = 0.035 + 0.010 * (height - 1.04) / 0.14
    ixx = mass * (3.0 * collision_radius * collision_radius + height * height) / 12.0
    izz = mass * collision_radius * collision_radius / 2.0

    return {
        "name": f"contact_bush_{index:03d}",
        "x": x,
        "y": y,
        "center_z": center_z,
        "height": height,
        "collision_radius": collision_radius,
        "collision_length": collision_length,
        "leaf_radius": leaf_radius,
        "leaf_z": height * 0.22,
        "yaw": yaw,
        "mass": mass,
        "ixx": ixx,
        "izz": izz,
        "spring_stiffness": spring_stiffness,
        "damping": damping,
    }


def bush_to_sdf(bush):
    return f"""
    <link name="{bush['name']}">
      <pose relative_to="__model__">{bush['x']:.3f} {bush['y']:.3f} {bush['center_z']:.3f} 0 0 {bush['yaw']:.3f}</pose>
      <self_collide>false</self_collide>
      <inertial>
        <mass>{bush['mass']:.4f}</mass>
        <inertia>
          <ixx>{bush['ixx']:.6f}</ixx>
          <iyy>{bush['ixx']:.6f}</iyy>
          <izz>{bush['izz']:.6f}</izz>
        </inertia>
      </inertial>
      <visual name="stem_visual">
        <geometry>
          <cylinder>
            <radius>0.035</radius>
            <length>{bush['height']:.3f}</length>
          </cylinder>
        </geometry>
        <material>
          <ambient>0.07 0.35 0.09 1</ambient>
          <diffuse>0.12 0.62 0.16 1</diffuse>
          <specular>0.03 0.08 0.03 1</specular>
        </material>
      </visual>
      <visual name="leaf_cluster_visual">
        <pose>0 0 {bush['leaf_z']:.3f} 0 0 0</pose>
        <geometry>
          <sphere>
            <radius>{bush['leaf_radius']:.3f}</radius>
          </sphere>
        </geometry>
        <material>
          <ambient>0.05 0.34 0.08 1</ambient>
          <diffuse>0.12 0.68 0.18 1</diffuse>
          <specular>0.02 0.07 0.02 1</specular>
        </material>
      </visual>
      <collision name="soft_collision">
        <pose>0 0 {-(bush['height'] - bush['collision_length']) / 2.0:.3f} 0 0 0</pose>
        <surface>
          <friction>
            <ode>
              <mu>0.01</mu>
              <mu2>0.01</mu2>
            </ode>
          </friction>
        </surface>
        <geometry>
          <cylinder>
            <radius>{bush['collision_radius']:.3f}</radius>
            <length>{bush['collision_length']:.3f}</length>
          </cylinder>
        </geometry>
      </collision>
    </link>
    <joint name="{bush['name']}_spring_joint" type="revolute">
      <pose relative_to="{bush['name']}">0 0 {-bush['height'] / 2.0:.3f} 0 0 0</pose>
      <parent>world</parent>
      <child>{bush['name']}</child>
      <axis>
        <xyz expressed_in="__model__">0 1 0</xyz>
        <limit>
          <lower>-1.55</lower>
          <upper>1.55</upper>
          <effort>10</effort>
          <velocity>12</velocity>
        </limit>
        <dynamics>
          <damping>{bush['damping']:.3f}</damping>
          <spring_reference>0</spring_reference>
          <spring_stiffness>{bush['spring_stiffness']:.3f}</spring_stiffness>
        </dynamics>
      </axis>
    </joint>
"""


def write_outputs(target_dir, bushes):
    os.makedirs(target_dir, exist_ok=True)

    sdf = """<?xml version="1.0" ?>
<!-- auto generated by generate_soft_vegetation_contact_field_model_sdf.py -->
<sdf version="1.10">
  <model name="soft_vegetation_contact_field">
    <static>false</static>
    <self_collide>false</self_collide>
"""
    for bush in bushes:
        sdf += bush_to_sdf(bush)
    sdf += """
  </model>
</sdf>
"""

    with open(os.path.join(target_dir, "model.sdf"), "w") as sdf_file:
        sdf_file.write(sdf)

    with open(os.path.join(target_dir, "contact_positions.csv"), "w", newline="") as csv_file:
        writer = csv.writer(csv_file)
        writer.writerow(
            [
                "name",
                "x",
                "y",
                "center_z",
                "height",
                "collision_radius",
                "collision_length",
                "leaf_radius",
            ]
        )
        for bush in bushes:
            writer.writerow(
                [
                    bush["name"],
                    f"{bush['x']:.3f}",
                    f"{bush['y']:.3f}",
                    f"{bush['center_z']:.3f}",
                    f"{bush['height']:.3f}",
                    f"{bush['collision_radius']:.3f}",
                    f"{bush['collision_length']:.3f}",
                    f"{bush['leaf_radius']:.3f}",
                ]
            )


def main():
    rng = random.Random(RANDOM_SEED)
    bushes = [make_bush(index, x, y, rng) for index, (x, y) in enumerate(CONTACT_POINTS)]
    target_dir = argv[1] if len(argv) > 1 else os.path.dirname(__file__)
    write_outputs(target_dir, bushes)


if __name__ == "__main__":
    main()
